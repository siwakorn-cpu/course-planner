function buildClasses(): ClassRoom[] {
  const c = (
    grade: ClassRoom['grade'],
    section: string,
    plan: string,
    students: number,
    cohort: string,
  ): ClassRoom => ({ id: id('cls'), grade, section, plan, students, cohort });

  // รุ่น = ปีที่นักเรียนเข้าเรียน ม.1 (ตัวอย่าง: ม.1 รุ่น 69, ม.4 เข้ามาก่อน 3 ปี = รุ่น 66)
  return [
    c('ม.1', '1', 'ทั่วไป', 40, '69'),
    c('ม.1', '2', 'ทั่วไป', 38, '69'),
    c('ม.4', '1', 'วิทย์-คณิต', 36, '66'),
    c('ม.4', '2', 'ศิลป์-ภาษา', 34, '66'),
    // ห้องรวม: ม.5/5,6,7 เรียนพื้นฐานร่วมกัน แต่แยกวิชาเพิ่มเติมเป็นกลุ่มย่อย 5/5, 5/6, 5/7
    c('ม.5', '5,6,7', 'ศิลป์-ทั่วไป', 105, '65'),
  ];
}

function buildOfferings(
  subjects: Subject[],
  classes: ClassRoom[],
  teachers: Record<string, Teacher>,
): Offering[] {
  const byCode = new Map(subjects.map((s) => [s.code, s]));
  const offerings: Offering[] = [];
  const add = (cls: ClassRoom, code: string, semester: Offering['semester'], teacherKey: string, group?: string) => {
    const subj = byCode.get(code);
    if (!subj) return;
    offerings.push({
      id: id('off'),
      classId: cls.id,
      subjectId: subj.id,
      semester,
      teacherId: teachers[teacherKey]?.id,
      group,
    });
  };

  const m11 = classes.find((c) => c.grade === 'ม.1' && c.section === '1')!;
  const m41 = classes.find((c) => c.grade === 'ม.4' && c.section === '1')!;
  const m567 = classes.find((c) => c.grade === 'ม.5' && c.section === '5,6,7')!;

  // ม.1/1 ภาคเรียนที่ 1 : ชุดวิชาพื้นฐาน + เพิ่มเติม (จับคู่ครูตามกลุ่มสาระ)
  add(m11, 'ท21101', 1, 'ไทย');
  add(m11, 'ค21101', 1, 'คณิต');
  add(m11, 'ค21201', 1, 'คณิต');
  add(m11, 'ว21101', 1, 'วิทย์');
  add(m11, 'ว21103', 1, 'คอม');
  add(m11, 'ส21101', 1, 'สังคม');
  add(m11, 'ส21102', 1, 'สังคม');
  add(m11, 'พ21101', 1, 'พละ');
  add(m11, 'พ21102', 1, 'พละ');
  add(m11, 'ศ21101', 1, 'ศิลปะ');
  add(m11, 'ง21101', 1, 'การงาน');
  add(m11, 'อ21101', 1, 'อังกฤษ');
  add(m11, 'อ21201', 1, 'อังกฤษ');
  add(m11, 'ก21901', 1, 'กิจกรรม');

  // ม.4/1 (วิทย์-คณิต) ภาคเรียนที่ 1
  add(m41, 'ท31101', 1, 'ไทย');
  add(m41, 'ค31101', 1, 'คณิต');
  add(m41, 'ค31201', 1, 'คณิต');
  add(m41, 'ว31101', 1, 'วิทย์');
  add(m41, 'ว31201', 1, 'ฟิสิกส์');
  add(m41, 'ว31221', 1, 'เคมี');
  add(m41, 'ว31241', 1, 'ชีวะ');
  add(m41, 'ส31101', 1, 'สังคม');
  add(m41, 'พ31101', 1, 'พละ');
  add(m41, 'ศ31101', 1, 'ศิลปะ');
  add(m41, 'ง31101', 1, 'การงาน');
  add(m41, 'อ31101', 1, 'อังกฤษ');
  add(m41, 'อ31201', 1, 'อังกฤษ');
  add(m41, 'ก31901', 1, 'กิจกรรม');

  // ม.5/5,6,7 ภาคเรียนที่ 1
  //  - วิชาพื้นฐาน: เรียนร่วมทั้งห้อง (เว้นกลุ่ม) -> ครูสอน 1 ชุดคาบ
  add(m567, 'ท31101', 1, 'ไทย');
  add(m567, 'ค31101', 1, 'คณิต');
  add(m567, 'ว31101', 1, 'วิทย์');
  add(m567, 'ส31101', 1, 'สังคม');
  add(m567, 'พ31101', 1, 'พละ');
  add(m567, 'ศ31101', 1, 'ศิลปะ');
  add(m567, 'ง31101', 1, 'การงาน');
  add(m567, 'อ31101', 1, 'อังกฤษ');
  add(m567, 'ก31901', 1, 'กิจกรรม');
  //  - วิชาเพิ่มเติม: แยกกลุ่มย่อย (แต่ละห้องเลือกต่างกัน) -> ครูสอนแยกคาบ
  add(m567, 'ว31201', 1, 'ฟิสิกส์', '5/5'); // 5/5 เน้นวิทย์
  add(m567, 'ว31221', 1, 'เคมี', '5/5');
  add(m567, 'ว31241', 1, 'ชีวะ', '5/6'); // 5/6 เน้นชีวะ-คณิต
  add(m567, 'ค31201', 1, 'คณิต', '5/6');
  add(m567, 'อ31201', 1, 'อังกฤษ', '5/7'); // 5/7 เน้นภาษา

  return offerings;
}

/** หน่วยกิตเดิม (วิชา ม.4 ที่เรียนจบแล้ว) ของห้องรวม ม.5/5,6,7 เพื่อโชว์หน่วยกิตสะสม */
function buildCompleted(classes: ClassRoom[]): AppData['completed'] {
  const m567 = classes.find((c) => c.grade === 'ม.5' && c.section === '5,6,7');
  if (!m567) return [];
  const d = (
    code: string,
    name: string,
    credits: number,
    type: Subject['type'],
    group?: string,
  ) => ({ id: id('done'), classId: m567.id, code, name, credits, type, group, note: 'ม.4 (2565)' });
  return [
    // พื้นฐาน ม.4 (เรียนร่วม)
    d('ท30101', 'ภาษาไทย (ม.4)', 2.0, 'พื้นฐาน'),
    d('ค30101', 'คณิตศาสตร์ (ม.4)', 2.0, 'พื้นฐาน'),
    d('ว30101', 'วิทยาศาสตร์ (ม.4)', 2.0, 'พื้นฐาน'),
    // เพิ่มเติม ม.4 แยกกลุ่มย่อย
    d('ว30201', 'ฟิสิกส์ (ม.4)', 1.5, 'เพิ่มเติม', '5/5'),
    d('ว30221', 'เคมี (ม.4)', 1.5, 'เพิ่มเติม', '5/5'),
    d('ว30241', 'ชีววิทยา (ม.4)', 1.5, 'เพิ่มเติม', '5/6'),
    d('ค30201', 'คณิตศาสตร์เพิ่มเติม (ม.4)', 2.0, 'เพิ่มเติม', '5/6'),
    d('อ30201', 'ภาษาอังกฤษอ่าน-เขียน (ม.4)', 1.0, 'เพิ่มเติม', '5/7'),
  ];
}

/** สร้างชุดข้อมูลตัวอย่างสด ๆ (id ไม่ซ้ำกันทุกครั้งที่เรียก) */
export function seedData(): AppData {
  counter = 0;
  const subjects = buildSubjects();
  const teacherMap = buildTeachers();
  const classes = buildClasses();
  const offerings = buildOfferings(subjects, classes, teacherMap);
  return {
    version: DATA_VERSION,
    subjects,
    classes,
    offerings,
    teachers: Object.values(teacherMap),
    completed: buildCompleted(classes),
    graduated: [],
    plans: [...DEFAULT_PLANS],
    groups: [...DEFAULT_GROUPS],
    settings: structuredClone(DEFAULT_SETTINGS),
  };
}
